#!/usr/bin/env node
/**
 * The pinyin initial of every BMP hanzi, as one table, for the kits that have no pinyin collation.
 *
 * Vue and SwiftUI ask the platform (`Intl.Collator("zh-Hans-u-co-pinyin")`, `applyingTransform(.toLatin)`).
 * Flutter has neither, and Compose's ICU transliterator only arrived in Android 10 — so Flutter shipped
 * a table of the 3,755 GB2312 level-1 hanzi and Compose fell back to "#" on Android 8 and 9. Both are
 * FR-044's remainder: a name starting with a level-2 character (梓 琪 苒 珩 婧), or with anything at all
 * on an Android 9 phone, landed in the hash bucket next to the emoji.
 *
 * This writes all 20,992 characters of CJK Unified Ideographs (U+4E00–U+9FFF) in pinyin order, plus
 * the 23 offsets where the initial letter changes — the same shape as the table it replaces, six times
 * wider. The order is what sorts names inside a letter, so it is kept, not just the letter.
 *
 * The order is the platform's own pinyin collation, read here the way the Vue kit reads it at runtime,
 * so the four kits cannot disagree. A polyphonic character follows the collation's reading, which also
 * settles the last of FR-044: 曾 was Z on Flutter (GB2312 put it there) and C everywhere else, and is
 * now C on all four. A host that knows a surname's reading still passes `indexKey`.
 *
 * Characters outside the block go to "#", the same as on Vue and SwiftUI.
 *
 * Run through `npm run generate`; `--check` fails when a generated file is stale.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const vueIndex = join(root, "packages/vue-im-ui/src/utils/contactIndex.ts");

const FIRST = 0x4e00;
const LAST = 0x9fff;
const OTHER = "#";

/** The letters and boundaries come from the Vue kit, so there is one copy of the rule, not two. */
function ruleFromVue() {
  const source = readFileSync(vueIndex, "utf8");
  const letters = /const PINYIN_LETTERS = "([A-Z]+)";/.exec(source)?.[1];
  const boundaries = /const PINYIN_BOUNDARIES = "([^"]+)";/.exec(source)?.[1];
  const sentinels = [...source.matchAll(/\["(.)", "([A-Z])"\]/g)].map((m) => [m[1], m[2]]);
  if (!letters || !boundaries || letters.length !== [...boundaries].length || !sentinels.length) {
    throw new Error(`could not read the index rule from ${relative(root, vueIndex)}`);
  }
  return { letters, boundaries: [...boundaries], sentinels };
}

const { letters, boundaries, sentinels } = ruleFromVue();
const collator = new Intl.Collator("zh-Hans-u-co-pinyin");

function initial(character) {
  let letter = OTHER;
  for (let index = 0; index < boundaries.length; index += 1) {
    if (collator.compare(boundaries[index], character) > 0) break;
    letter = letters[index];
  }
  return letter;
}

// The generator runs on whatever Node this machine has; if its ICU has no pinyin collation the table
// would be 20,992 hash marks and look like a valid build. The same sentinels the Vue kit checks.
for (const [character, expected] of sentinels) {
  const actual = initial(character);
  if (actual !== expected) {
    console.error(`pinyin initials: this Node has no pinyin collation (${character} read as "${actual}", not "${expected}")`);
    console.error(`  The table cannot be generated here. Use a Node built with full ICU.`);
    process.exit(1);
  }
}

const ordered = [];
for (let code = FIRST; code <= LAST; code += 1) ordered.push(String.fromCodePoint(code));
ordered.sort(collator.compare);

// Where each letter starts in that order. A character's letter is the letter of the last offset at
// or before its position, which is also how the Vue kit reads the boundaries at runtime.
const offsets = [];
for (const boundary of boundaries) {
  let low = 0;
  let high = ordered.length;
  while (low < high) {
    const mid = (low + high) >> 1;
    if (collator.compare(ordered[mid], boundary) < 0) low = mid + 1; else high = mid;
  }
  offsets.push(low);
}
if (offsets[0] !== 0) throw new Error(`the first boundary is at ${offsets[0]}, not 0: the block starts before A`);
for (let index = 1; index < offsets.length; index += 1) {
  if (offsets[index] <= offsets[index - 1]) throw new Error(`letter ${letters[index]} starts at or before ${letters[index - 1]}`);
}

const table = ordered.join("");
const spread = letters.split("").map((letter, index) =>
  `${letter}:${(offsets[index + 1] ?? table.length) - offsets[index]}`).join(" ");

/** Rows so a diff points at a range of characters rather than at one 20,992-column line. */
function rows(text, width = 328) {
  const out = [];
  for (let at = 0; at < text.length; at += width) out.push(text.slice(at, at + width));
  return out;
}

const banner = (comment) => [
  `${comment} GENERATED by tooling/build-pinyin-initials.mjs. Do not edit; run \`npm run generate\`.`,
  `${comment}`,
  `${comment} Every character in CJK Unified Ideographs (U+4E00-U+9FFF) in pinyin order, plus where`,
  `${comment} each initial letter starts. A character's letter is the letter of the last offset at or`,
  `${comment} before its position, and its position orders names within a letter.`,
  `${comment}`,
  `${comment} The order is the platform pinyin collation the Vue kit reads at runtime, so the four kits`,
  `${comment} cannot disagree: a polyphonic character follows the collation's reading (曾 is C on all`,
  `${comment} four), and a host that knows a surname's reading passes its own index key. A character`,
  `${comment} outside the block indexes as "#", the same as on Vue and SwiftUI.`,
].join("\n");

const dart = `${banner("//")}
library;

const String _ordered =
${rows(table).map((row) => `    '${row}'`).join("\n")};

const List<int> _offsets = <int>[
${offsets.map((offset) => `  ${offset},`).join("\n")}
];

const String _letters = '${letters}';

Map<int, int>? _positions;

/// Where [rune] sits in pinyin order (0 for the first hanzi, ${table.length - 1} for the last), or -1
/// when it is not a hanzi this table covers.
int flarePinyinPosition(int rune) {
  final positions = _positions ??= {
    for (var i = 0; i < _ordered.length; i++) _ordered.codeUnitAt(i): i,
  };
  return positions[rune] ?? -1;
}

/// The pinyin initial ('A'..'Z', never I, U or V) of a hanzi, or null for any other character.
String? flarePinyinInitial(int rune) {
  final position = flarePinyinPosition(rune);
  if (position < 0) return null;
  var low = 0;
  var high = _offsets.length - 1;
  while (low < high) {
    final mid = (low + high + 1) >> 1;
    if (_offsets[mid] <= position) {
      low = mid;
    } else {
      high = mid - 1;
    }
  }
  return _letters[low];
}
`;

// Kotlin joins rows at first use: one string constant of every character would be 63 KB of modified
// UTF-8, close enough to the class file's 64 KB limit per constant to be worth not finding out.
const kotlin = `${banner("//")}
package com.flare.im.ui

private val ORDERED_ROWS = arrayOf(
${rows(table).map((row) => `    "${row}",`).join("\n")}
)

private val OFFSETS = intArrayOf(${offsets.join(", ")})

private const val LETTERS = "${letters}"

private val positions: Map<Char, Int> by lazy {
    val map = HashMap<Char, Int>(${table.length} * 2)
    var index = 0
    for (row in ORDERED_ROWS) for (character in row) map[character] = index++
    map
}

/** Where [character] sits in pinyin order, or -1 when it is not a hanzi this table covers. */
internal fun flarePinyinPosition(character: Char): Int = positions[character] ?: -1

/** The pinyin initial ('A'..'Z', never I, U or V) of a hanzi, or null for any other character. */
internal fun flarePinyinInitial(character: Char): Char? {
    val position = flarePinyinPosition(character)
    if (position < 0) return null
    var low = 0
    var high = OFFSETS.size - 1
    while (low < high) {
        val mid = (low + high + 1) ushr 1
        if (OFFSETS[mid] <= position) low = mid else high = mid - 1
    }
    return LETTERS[low]
}
`;

const outputs = [
  [join(root, "packages/flutter-im-ui/lib/src/utils/pinyin_initials.dart"), dart],
  [join(root, "packages/android-im-ui/src/main/kotlin/com/flare/im/ui/PinyinInitials.kt"), kotlin],
];

const check = process.argv.includes("--check");
const stale = [];
for (const [file, content] of outputs) {
  let current = null;
  try { current = readFileSync(file, "utf8"); } catch { /* not written yet */ }
  if (current === content) continue;
  if (check) { stale.push(relative(root, file)); continue; }
  writeFileSync(file, content);
}

if (check) {
  if (stale.length) {
    console.error(`pinyin initials are stale: ${stale.join(", ")} — run \`node tooling/build-pinyin-initials.mjs\``);
    process.exit(1);
  }
  console.log(`generated pinyin initials: current (${table.length} characters, ${letters.length} letters)`);
} else {
  console.log(`pinyin initials written for ${outputs.length} platforms: ${table.length} characters\n  ${spread}`);
}
