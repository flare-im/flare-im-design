#!/usr/bin/env node
// 四端组件目录里「宿主无法从根部覆盖」的中文字面量棘轮。
//
// 每端都有 strings provider（Vue messages.ts / Flutter FlareStrings / iOS FlareStrings /
// Compose FlareStrings），但组件默认文案长期直接写在源码里：构造参数默认值、withDefaults、
// Labels 类默认值、内联字面量。宿主要换语言就得逐 prop 传——这不是「通用」。
// 这里统计每端源码（排除 strings 文件、Preview、测试、注释）里含 CJK 的字符串字面量，
// 与 tooling/hardcoded-strings-baseline.json 比：只允许下降。`--baseline` 重写基线。
import { readFileSync, readdirSync, statSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const baselinePath = join(here, "hardcoded-strings-baseline.json");

const TARGETS = {
  vue: { dir: "packages/vue-im-ui/src/components", ext: [".vue", ".ts"], skip: [/\.test\.ts$/, /i18n\//] },
  flutter: { dir: "packages/flutter-im-ui/lib/src", ext: [".dart"], skip: [/flare_strings\.dart$/] },
  ios: { dir: "packages/ios-im-ui/Sources/FlareIMUI", ext: [".swift"], skip: [/FlareStrings\.swift$/, /Previews\.swift$/] },
  compose: { dir: "packages/android-im-ui/src/main/kotlin", ext: [".kt"], skip: [/FlareStrings\.kt$/, /Previews?\.kt$/] },
  // 示例 app 也进棘轮。它一度攒到 543 处裸中文,于是「切换语言」按下去满屏还是中文 ——
  // 开关一直是好的,缺的是第二种语言。参考实现的文案同样要走 provider,否则这笔债会再长回来。
  // 目录是同级 checkout;没有它(单独 clone 本仓)时 walk() 返回空,这一项自动跳过。
  webApp: {
    dir: "../flare-social/flare-social-sdk/examples/apps/flare-social-web-app/src",
    ext: [".vue", ".ts"],
    skip: [/\.test\.ts$/, /\/i18n\//],
  },
};
const CJK = /[一-鿿]/;

function walk(dir, ext) {
  const out = [];
  if (!existsSync(dir)) return out;
  for (const n of readdirSync(dir)) {
    const p = join(dir, n);
    if (statSync(p).isDirectory()) out.push(...walk(p, ext));
    else if (ext.some((e) => p.endsWith(e))) out.push(p);
  }
  return out;
}

function stripComments(src, isVue) {
  let out = "", i = 0;
  while (i < src.length) {
    const two = src.slice(i, i + 2);
    if (two === "//") { while (i < src.length && src[i] !== "\n") i++; }
    else if (two === "/*") { const e = src.indexOf("*/", i + 2); i = e === -1 ? src.length : e + 2; }
    else if (isVue && src.startsWith("<!--", i)) { const e = src.indexOf("-->", i); i = e === -1 ? src.length : e + 3; }
    else out += src[i++];
  }
  return out;
}

/** 返回含 CJK 的字符串字面量数量（"…" '…' `…` 三种引号；Vue 模板里的裸中文文本也算） */
function countLiterals(src, isVue) {
  let n = 0;
  for (const m of src.matchAll(/"([^"\\\n]|\\.)*"|'([^'\\\n]|\\.)*'|`([^`\\]|\\.)*`/g)) if (CJK.test(m[0])) n++;
  if (isVue) {
    // 模板文本节点：>中文< 形式
    const tpl = src.match(/<template>[\s\S]*<\/template>/)?.[0] ?? "";
    for (const m of tpl.matchAll(/>([^<>{}]*)</g)) if (CJK.test(m[1])) n++;
  }
  return n;
}

const args = process.argv.slice(2);
const result = {};
for (const [platform, t] of Object.entries(TARGETS)) {
  const files = walk(join(root, t.dir), t.ext).filter((f) => !t.skip.some((re) => re.test(f)));
  let total = 0;
  const perFile = {};
  for (const f of files) {
    const isVue = f.endsWith(".vue");
    const source = readFileSync(f, "utf8");
    // A generated file holds data, not copy. `PinyinInitials.kt` and `pinyin_initials.dart` are 20,992
    // hanzi each — a contact index's table, with nobody to translate it for.
    if (/^.{0,4}\s*GENERATED by /m.test(source.slice(0, 400))) continue;
    const c = countLiterals(stripComments(source, isVue), isVue);
    if (c) { perFile[relative(root, f)] = c; total += c; }
  }
  result[platform] = { total, files: perFile };
}

if (args.includes("--baseline")) {
  writeFileSync(baselinePath, JSON.stringify(Object.fromEntries(Object.entries(result).map(([p, r]) => [p, r.total])), null, 2) + "\n");
  console.log("baseline written:", Object.entries(result).map(([p, r]) => `${p}=${r.total}`).join(" "));
  process.exit(0);
}
if (args.includes("--list")) {
  for (const [p, r] of Object.entries(result)) {
    console.log(`== ${p} ${r.total}`);
    for (const [f, c] of Object.entries(r.files).sort((a, b) => b[1] - a[1]).slice(0, args.includes("--all") ? 1e9 : 15)) console.log(`  ${String(c).padStart(4)}  ${f}`);
  }
}
const baseline = existsSync(baselinePath) ? JSON.parse(readFileSync(baselinePath, "utf8")) : null;
let failed = false;
for (const [p, r] of Object.entries(result)) {
  const b = baseline?.[p];
  const status = b == null ? "(no baseline)" : r.total > b ? `✗ up from ${b}` : r.total < b ? `↓ from ${b} — run --baseline to lock it in` : "= baseline";
  if (b != null && r.total > b) failed = true;
  console.log(`${p.padEnd(8)} ${String(r.total).padStart(4)} hard-coded CJK literals ${status}`);
}
if (failed) {
  console.error("\n✗ hard-coded copy increased — route new text through the platform strings provider (Vue useFlareI18n().t / Flutter FlareStrings.of / iOS @Environment(\\.flareStrings) / Compose flareStrings()).");
  process.exit(1);
}
