#!/usr/bin/env node
/**
 * Generates each design kit's PLUGIN_UI_VOCABULARY from spec/plugin-ui-vocabulary.json, the single source.
 *
 * A host passes the constant to the engine as `kitVocabulary` (plugin.set_host_profile). It must name only what the
 * kit renders: the shared vocabulary minus the kit's `omit` sets. The output is the wire shape of
 * flare-plugin-protocol `UiVocabulary` ({version, blocks, inputs, formats, actions, native, renderers, kinds}), every
 * set sorted.
 *
 *   node spec/build-plugin-ui-vocabulary.mjs                      write every kit's file
 *   node spec/build-plugin-ui-vocabulary.mjs --kits vue,flutter   write only these kits
 *   node spec/build-plugin-ui-vocabulary.mjs --check              fail if a written file is out of date
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const check = process.argv.includes("--check");
const kitsArg = process.argv.find((arg) => arg.startsWith("--kits"));
const kitsIndex = process.argv.indexOf("--kits");
const only = kitsArg?.includes("=")
  ? kitsArg.split("=")[1].split(",")
  : kitsIndex >= 0
    ? (process.argv[kitsIndex + 1] ?? "").split(",")
    : null;

const source = JSON.parse(readFileSync(join(here, "plugin-ui-vocabulary.json"), "utf8"));
const SETS = ["blocks", "inputs", "formats", "actions", "native", "renderers", "kinds"];
const NAME = /^[A-Za-z0-9._-]{1,64}$/;

const shared = source.vocabulary;
if (!Number.isInteger(shared.version) || shared.version < 1) throw new Error("vocabulary.version must be a positive integer");
for (const set of SETS) {
  const names = shared[set] ?? [];
  if (!Array.isArray(names)) throw new Error(`vocabulary.${set} must be a list`);
  if (names.length > 128) throw new Error(`vocabulary.${set}: more than 128 names`);
  for (const name of names) if (!NAME.test(name)) throw new Error(`vocabulary.${set}: bad name ${JSON.stringify(name)}`);
  if (new Set(names).size !== names.length) throw new Error(`vocabulary.${set}: duplicate names`);
}

/** The vocabulary `kit` reports: every shared set without the kit's omitted names, sorted. */
function vocabularyOf(kit) {
  const omit = source.kits?.[kit]?.omit ?? {};
  for (const [set, names] of Object.entries(omit)) {
    if (!SETS.includes(set)) throw new Error(`kits.${kit}.omit.${set}: not a vocabulary set`);
    for (const name of names) {
      if (!(shared[set] ?? []).includes(name)) throw new Error(`kits.${kit}.omit.${set}: ${name} is not in the vocabulary`);
    }
  }
  const out = { version: shared.version };
  for (const set of SETS) {
    const dropped = new Set(omit[set] ?? []);
    out[set] = [...(shared[set] ?? [])].filter((name) => !dropped.has(name)).sort();
  }
  return out;
}

const BANNER = "Generated by spec/build-plugin-ui-vocabulary.mjs from spec/plugin-ui-vocabulary.json — do not edit by hand.";
const list = (names, quote, indent) =>
  names.length ? `\n${names.map((name) => `${indent}${quote}${name}${quote},`).join("\n")}\n${indent.slice(2)}` : "";

const targets = {
  vue: {
    path: "packages/vue-im-ui/src/shared/contracts/plugin-ui-vocabulary.ts",
    render: (v) => `// ${BANNER}

/** The wire shape of flare-plugin-protocol \`UiVocabulary\`: the names a party renders. */
export interface FlarePluginUiVocabulary {
  version: number;
${SETS.map((set) => `  ${set}: ReadonlyArray<string>;`).join("\n")}
}

/**
 * What this kit renders: the host passes it as \`kitVocabulary\` to the engine (\`plugin.set_host_profile\`), which
 * reports to Core only what both the engine and this kit read.
 */
export const PLUGIN_UI_VOCABULARY: FlarePluginUiVocabulary = Object.freeze({
  version: ${v.version},
${SETS.map((set) => `  ${set}: Object.freeze([${list(v[set], '"', "    ")}]),`).join("\n")}
});
`,
  },
  flutter: {
    path: "packages/flutter-im-ui/lib/src/models/plugin_ui_vocabulary.dart",
    render: (v) => `// ${BANNER}

/// What this kit renders, in the wire shape of flare-plugin-protocol
/// \`UiVocabulary\`. The host passes it as \`kitVocabulary\` to the engine
/// (\`plugin.set_host_profile\`), which reports to Core only what both the
/// engine and this kit read.
// ignore: constant_identifier_names
const Map<String, Object> PLUGIN_UI_VOCABULARY = <String, Object>{
  'version': ${v.version},
${SETS.map((set) => `  '${set}': <String>[${list(v[set], "'", "    ")}],`).join("\n")}
};
`,
  },
  android: {
    path: "packages/android-im-ui/src/main/kotlin/com/flare/im/ui/PluginUiVocabulary.kt",
    render: (v) => `// ${BANNER}

package com.flare.im.ui

/**
 * What this kit renders, as the JSON of flare-plugin-protocol \`UiVocabulary\`. The host passes it as
 * \`kitVocabulary\` to the engine (\`plugin.set_host_profile\`).
 */
const val PLUGIN_UI_VOCABULARY: String = ${JSON.stringify(JSON.stringify(v)).replace(/\$/g, "\\$")}

/** The same vocabulary as sets. */
object PluginUiVocabulary {
    const val VERSION: Int = ${v.version}
${SETS.map((set) => `    val ${set}: Set<String> = setOf(${v[set].map((n) => `"${n}"`).join(", ")})`).join("\n")}
}
`,
  },
  ios: {
    path: "packages/ios-im-ui/Sources/FlareIMUI/Components/PluginUIVocabulary.swift",
    render: (v) => `// ${BANNER}

import Foundation

/// What this kit renders, as the JSON of flare-plugin-protocol \`UiVocabulary\`. The host passes it as
/// \`kitVocabulary\` to the engine (\`plugin.set_host_profile\`).
public let PLUGIN_UI_VOCABULARY: String = ${JSON.stringify(JSON.stringify(v))}

/// The same vocabulary as sets.
public enum FlarePluginUIVocabulary {
    public static let version = ${v.version}
${SETS.map((set) => `    public static let ${set}: Set<String> = [${v[set].map((n) => `"${n}"`).join(", ")}]`).join("\n")}
}
`,
  },
};

let stale = 0;
for (const [kit, target] of Object.entries(targets)) {
  if (only && !only.includes(kit)) continue;
  const path = join(root, target.path);
  const next = target.render(vocabularyOf(kit));
  const current = existsSync(path) ? readFileSync(path, "utf8") : null;
  if (current === next) {
    console.log(`${kit}: up to date`);
    continue;
  }
  if (check) {
    // A kit whose file was never written is reported only when asked for by name.
    if (current === null && !only) {
      console.log(`${kit}: not generated (run with --kits ${kit})`);
      continue;
    }
    console.error(`${kit}: OUT OF DATE — run \`node spec/build-plugin-ui-vocabulary.mjs --kits ${kit}\``);
    stale += 1;
    continue;
  }
  writeFileSync(path, next);
  console.log(`${kit}: wrote ${target.path}`);
}
if (stale) process.exit(1);
