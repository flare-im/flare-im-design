import { readFileSync, writeFileSync } from 'node:fs';
const read = path => JSON.parse(readFileSync(new URL(path, import.meta.url), 'utf8'));
const spec = read('./components.json'), coverage = read('./im-coverage.json');
const names = new Set(spec.components.map(c => c.name));
const ids = new Set();
for (const area of coverage.areas) {
  if (ids.has(area.id)) throw Error(`Duplicate coverage area: ${area.id}`);
  ids.add(area.id);
  if (!['P0', 'P1', 'P2', 'P3'].includes(area.phase) || !area.requiredStates || !area.next) throw Error(`Incomplete area: ${area.id}`);
  for (const c of area.components) if (!names.has(c)) throw Error(`Unknown component ${c} in ${area.id}`);
}
const output = `<!-- GENERATED by spec/build-im-coverage.mjs; edit spec/im-coverage.json. -->
# IM 场景覆盖矩阵

当前契约：${names.size} 项组件，${new Set(spec.components.map(c => c.category)).size} 个组件类别；按 ${coverage.areas.length} 个 IM 场景检查。

${coverage.scope}

| 场景 | 阶段 | 已有组件基础 | 必须覆盖的状态 | 后续落地/验收 |
|---|---|---|---|---|
${coverage.areas.map(a => `| ${a.name} | ${a.phase} | ${a.components.join('、')} | ${a.requiredStates} | ${a.next} |`).join('\n')}

P0 为核心可靠性与跨设备基础，P1 为常用业务流程，P2 为高级能力与插件集成，P3 为可选社交扩展。阶段表示优先级，不表示已完成。
`;
const dest = new URL('../docs/IM-COVERAGE.md', import.meta.url);
if (process.argv.includes('--check')) {
  if (readFileSync(dest, 'utf8') !== output) throw Error('IM coverage documentation drift: run node spec/build-im-coverage.mjs');
} else writeFileSync(dest, output);
console.log(`IM coverage: ${coverage.areas.length} areas reference valid components (${names.size} total)`);
