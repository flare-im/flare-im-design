#!/usr/bin/env node
/**
 * Generates the English `FlareStrings` preset for the three native kits from
 * `strings/en.json`, the single source — the same shape as `tokens/build.mjs`.
 *
 * Why this exists: the native kits' `FlareStrings` are ~500-field structs whose
 * defaults are Chinese, designed to be overridden by the host. No second
 * language shipped, so a host had nothing to switch *to* and a language setting
 * could not do anything. The Vue kit is fully bilingual, but its message tree is
 * a different vocabulary (only ~14% of leaf names coincide), so it cannot feed
 * the native kits — hence a source of its own.
 *
 * `en.json` is keyed by field name and records, per field, the English string,
 * the Chinese default it was translated from (so a changed default is visible in
 * review) and which kits declare it. A field a kit does not declare is skipped
 * for that kit; the three kits' field sets overlap but are not identical.
 *
 * It also writes each native kit's resource keys: what a resource pack may name
 * (spec/resource-overlay-vectors.json). The strings come from the fields the kit
 * declares, the plain strings only, and the colours from `tokens/tokens.json`.
 *
 *   node strings/build.mjs            write the presets and the resource keys
 *   node strings/build.mjs --check    fail if they are out of date
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const check = process.argv.includes("--check");
const source = JSON.parse(readFileSync(join(here, "en.json"), "utf8"));

const BANNER = "// Generated by strings/build.mjs from strings/en.json — do not edit by hand.";
const KEYS_BANNER =
  "// Generated by strings/build.mjs from the kit's FlareStrings and tokens/tokens.json — do not edit by hand.";

// A plural's singular form is a field of its own (`<field>One`, marked `pluralOf: "<field>"`): every kit that
// declares it must declare the field it is the `one` form of (spec/plural-vectors.json).
for (const [field, entry] of Object.entries(source)) {
  if (!entry.pluralOf) continue;
  const other = source[entry.pluralOf];
  if (!other) throw new Error(`${field}: pluralOf names no field (${entry.pluralOf})`);
  const missing = entry.kits.filter((kit) => !other.kits.includes(kit));
  if (missing.length) throw new Error(`${field}: ${missing.join(", ")} declare it but not ${entry.pluralOf}`);
}

/**
 * Fields this kit declares.
 *
 * Swift requires named arguments in the order the initialiser declares them, so
 * the iOS list is read out of `FlareStrings.swift` rather than sorted — sorting
 * it alphabetically does not compile. Kotlin's builder and Dart's named
 * parameters do not care, so those stay sorted for a stable diff.
 */
function fieldsFor(kit) {
  const declared = Object.keys(source).filter((f) => source[f].kits.includes(kit));
  if (kit !== "ios") return declared.sort();
  const swift = readFileSync(
    join(root, "packages/ios-im-ui/Sources/FlareIMUI/Tokens/FlareStrings.swift"),
    "utf8",
  );
  const init = swift.slice(swift.indexOf("public init("));
  // A field that appends its argument (`appendArgumentKits`) is a `(String) -> String` closure on iOS.
  const order = [...init.matchAll(/^        (\w+): (?:String|@escaping @Sendable \(String\) -> String) = /gm)]
    .map((m) => m[1]);
  const known = new Set(declared);
  const ordered = order.filter((f) => known.has(f));
  const missing = declared.filter((f) => !order.includes(f));
  if (missing.length) {
    throw new Error(`ios: not in FlareStrings.init — ${missing.join(", ")}`);
  }
  return ordered;
}

/**
 * The plain string fields this kit declares, read out of its `FlareStrings`: a pack names a field the kit has, whether
 * or not `en.json` covers it, and a field that is a function has no text to replace.
 */
function stringFieldsFor(kit) {
  const read = (path) => readFileSync(join(root, path), "utf8");
  const fields = (text, pattern) => [...text.matchAll(pattern)].map((m) => m[1]);
  if (kit === "ios") {
    return fields(read("packages/ios-im-ui/Sources/FlareIMUI/Tokens/FlareStrings.swift"), /^    public var (\w+): String$/gm);
  }
  if (kit === "android") {
    const kotlin = read("packages/android-im-ui/src/main/kotlin/com/flare/im/ui/FlareStrings.kt");
    return fields(kotlin.slice(0, kotlin.indexOf("class FlareStringsBuilder")), /^    val (\w+): String$/gm);
  }
  const dart = read("packages/flutter-im-ui/lib/src/tokens/flare_strings.dart");
  const declared = fields(dart.slice(0, dart.indexOf("FlareStrings copyWith(")), /^  final String (\w+);$/gm);
  const copyWith = dart.slice(dart.indexOf("FlareStrings copyWith("));
  // A field `copyWith` does not take would silently fall back to its default in every folded word list.
  const missing = declared.filter((f) => !new RegExp(`\\b${f}:\\s*${f}\\s*\\?\\?\\s*this\\.${f}\\b`).test(copyWith));
  if (missing.length) throw new Error(`flutter: not in FlareStrings.copyWith — ${missing.join(", ")}`);
  return declared;
}

/** The native colour fields, as `tokens/build.mjs` names them: nested groups joined in camel case, in source order. */
function colorFieldsOf(colors, prefix = "") {
  return Object.entries(colors).flatMap(([key, value]) => {
    const name = prefix ? prefix + key[0].toUpperCase() + key.slice(1) : key;
    return value && typeof value === "object" ? colorFieldsOf(value, name) : [name];
  });
}
const colorFields = colorFieldsOf(JSON.parse(readFileSync(join(root, "tokens/tokens.json"), "utf8")).colors);

const swiftLiteral = (s) => `"${s.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
const kotlinLiteral = (s) =>
  `"${s.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\$/g, "\\$")}"`;
const dartLiteral = (s) => `'${s.replace(/\\/g, "\\\\").replace(/'/g, "\\'").replace(/\$/g, "\\$")}'`;

const targets = [
  {
    kit: "ios",
    path: join(root, "packages/ios-im-ui/Sources/FlareIMUI/Tokens/FlareStrings+English.swift"),
    render(fields) {
      const args = fields.map((f) => source[f].appendArgumentKits?.includes("ios")
        ? `            ${f}: { ${swiftLiteral(source[f].en)} + $0 }`
        : `            ${f}: ${swiftLiteral(source[f].en)}`).join(",\n");
      return `${BANNER}

import Foundation

public extension FlareStrings {
    /// The kit's component copy in English. Hosts apply it at the root:
    ///
    /// \`\`\`swift
    /// ContentView().flareStrings(.english)
    /// \`\`\`
    ///
    /// The defaults on \`FlareStrings\` stay Chinese; this is the second language,
    /// not a replacement. Fields the source does not cover keep their default. The
    /// fields that are functions of a count, a name or a kind come from
    /// \`englishFormats()\` (FlareStrings+EnglishFormats.swift, checked against
    /// strings/en-formats.json).
    static var english: FlareStrings {
        FlareStrings(
${args}
        ).englishFormats()
    }
}
`;
    },
  },
  {
    kit: "android",
    path: join(root, "packages/android-im-ui/src/main/kotlin/com/flare/im/ui/FlareStringsEnglish.kt"),
    render(fields) {
      const body = fields.map((f) => source[f].appendArgumentKits?.includes("android")
        ? `    ${f} = { value -> ${kotlinLiteral(source[f].en)} + value }`
        : `    ${f} = ${kotlinLiteral(source[f].en)}`).join("\n");
      return `${BANNER}

package com.flare.im.ui

/**
 * The kit's component copy in English. Hosts apply it at the root:
 *
 * \`\`\`kotlin
 * CompositionLocalProvider(LocalFlareStrings provides flareStringsEnglish()) { App() }
 * \`\`\`
 *
 * The defaults on [FlareStrings] stay Chinese; this is the second language, not a
 * replacement. Fields the source does not cover keep their default. The fields that
 * are functions of a count, a name or a kind come from [englishFormats]
 * (FlareStringsEnglishFormats.kt, checked against strings/en-formats.json).
 */
fun flareStringsEnglish(): FlareStrings = FlareStrings {
${body}
    englishFormats()
}
`;
    },
  },
  {
    kit: "flutter",
    path: join(root, "packages/flutter-im-ui/lib/src/tokens/flare_strings_english.dart"),
    render(fields) {
      const appends = fields.filter((f) => source[f].appendArgumentKits?.includes("flutter"));
      // The function fields' English is hand-written in the part file (checked against strings/en-formats.json):
      // every `_<field>English` it defines goes into the preset after the generated fields.
      const formatsSource = readFileSync(join(root, "packages/flutter-im-ui/lib/src/tokens/flare_strings_english_formats.dart"), "utf8");
      const formats = [...formatsSource.matchAll(/^String _(\w+)English\(/gm)].map((m) => m[1]).filter((f) => !fields.includes(f));
      const body = [
        ...fields.map((f) => `  ${f}: ${appends.includes(f) ? `_${f}English` : dartLiteral(source[f].en)},`),
        ...formats.map((f) => `  ${f}: _${f}English,`),
      ].join("\n");
      const functions = appends.map((f) => `String _${f}English(String value) => ${dartLiteral(source[f].en)} + value;`).join("\n");
      return `${BANNER}

import 'flare_strings.dart';

part 'flare_strings_english_formats.dart';

/// The kit's component copy in English. Hosts apply it at the root:
///
/// \`\`\`dart
/// FlareStringsScope(strings: flareStringsEnglish, child: app)
/// \`\`\`
///
/// The defaults on [FlareStrings] stay Chinese; this is the second language, not
/// a replacement. Fields the source does not cover keep their default. The fields
/// that are functions of a count, a name or a kind come from
/// flare_strings_english_formats.dart (checked against strings/en-formats.json).
const FlareStrings flareStringsEnglish = FlareStrings(
${body}
);
${functions ? `\n${functions}` : ""}
`;
    },
  },
  {
    kit: "ios",
    label: "ios resource keys",
    fields: () => stringFieldsFor("ios"),
    path: join(root, "packages/ios-im-ui/Sources/FlareIMUI/Tokens/FlareResourceKeys.swift"),
    render(fields) {
      return `${KEYS_BANNER}

import SwiftUI

extension FlareStrings {
    /// The text of the plain string field \`key\` names, or nil: a field that is a function is not a key.
    func stringValue(forKey key: String) -> String? {
        switch key {
${fields.map((f) => `        case "${f}": return self.${f}`).join("\n")}
        default: return nil
        }
    }

    /// Replaces the plain string field \`key\` names. A key that names none changes nothing.
    mutating func setStringValue(_ value: String, forKey key: String) {
        switch key {
${fields.map((f) => `        case "${f}": self.${f} = value`).join("\n")}
        default: break
        }
    }
}

/// The colours a resource pack may name.
let flareColorKeys: Set<String> = [
${colorFields.map((f) => `    "${f}",`).join("\n")}
]

extension FlareColors {
    /// These colours with the fields \`values\` names replaced.
    func applying(_ values: [String: Color]) -> FlareColors {
        copy(
${colorFields.map((f) => `            ${f}: values["${f}"]`).join(",\n")}
        )
    }
}
`;
    },
  },
  {
    kit: "android",
    label: "android resource keys",
    fields: () => stringFieldsFor("android"),
    path: join(root, "packages/android-im-ui/src/main/kotlin/com/flare/im/ui/FlareResourceKeys.kt"),
    render(fields) {
      return `${KEYS_BANNER}

package com.flare.im.ui

import androidx.compose.ui.graphics.Color

/** The plain string fields a resource pack may name. A field that is a function is not a key. */
internal val flareStringKeys: Set<String> = setOf(
${fields.map((f) => `    "${f}",`).join("\n")}
)

/** The text of the plain string field [key] names, or null. */
internal fun FlareStrings.stringValue(key: String): String? = when (key) {
${fields.map((f) => `    "${f}" -> this.${f}`).join("\n")}
    else -> null
}

/** The colours a resource pack may name. */
internal val flareColorKeys: Set<String> = setOf(
${colorFields.map((f) => `    "${f}",`).join("\n")}
)

/** These colours with the fields [values] names replaced. */
internal fun FlareColors.applying(values: Map<String, Color>): FlareColors = copy(
${colorFields.map((f) => `    ${f} = values["${f}"] ?: this.${f},`).join("\n")}
)
`;
    },
  },
  {
    kit: "flutter",
    label: "flutter resource keys",
    fields: () => stringFieldsFor("flutter"),
    path: join(root, "packages/flutter-im-ui/lib/src/tokens/flare_resource_keys.dart"),
    render(fields) {
      return `${KEYS_BANNER}

import 'dart:ui' show Color;

import 'flare_strings.dart';
import 'flare_tokens.dart';

/// The text of the plain string field [key] names, or null: a field that is a function is not a key.
String? flareStringValue(FlareStrings strings, String key) => switch (key) {
${fields.map((f) => `  '${f}' => strings.${f},`).join("\n")}
  _ => null,
};

/// [base] with the fields [values] names replaced.
FlareStrings flareStringsApplying(FlareStrings base, Map<String, String> values) => base.copyWith(
${fields.map((f) => `  ${f}: values['${f}'],`).join("\n")}
);

/// The colours a resource pack may name.
const Set<String> flareColorKeys = <String>{
${colorFields.map((f) => `  '${f}',`).join("\n")}
};

/// [base] with the fields [values] names replaced.
FlareColors flareColorsApplying(FlareColors base, Map<String, Color> values) => base.copyWith(
${colorFields.map((f) => `  ${f}: values['${f}'],`).join("\n")}
);
`;
    },
  },
];

let stale = 0;
for (const t of targets) {
  const label = t.label ?? t.kit;
  const fields = t.fields ? t.fields() : fieldsFor(t.kit);
  const next = t.render(fields);
  let current = null;
  try {
    current = readFileSync(t.path, "utf8");
  } catch {
    /* not written yet */
  }
  if (current === next) {
    console.log(`${label}: up to date (${fields.length} fields)`);
    continue;
  }
  if (check) {
    console.error(`${label}: OUT OF DATE — run \`node strings/build.mjs\``);
    stale += 1;
    continue;
  }
  writeFileSync(t.path, next);
  console.log(`${label}: wrote ${fields.length} fields → ${t.path.slice(root.length + 1)}`);
}
if (stale) process.exit(1);
