import SwiftUI

/// Inline component copy (accessibility labels, status hints, empty states…).
///
/// These strings used to be hard-coded inside view bodies, which left hosts with no way to
/// change the interface language of a cross-platform component kit. They now live in an
/// environment value whose defaults are still Chinese; a host that needs another language
/// overrides once at the root:
///
/// ```swift
/// ContentView().flareStrings(FlareStrings { $0.send = "Send" })
/// ```
///
/// Mirrors `FlareStrings` on Android (`LocalFlareStrings`) and the Flutter/Vue equivalents:
/// same field names, same defaults. Components that already take explicit `FlareXxxLabels`
/// parameters are unaffected — the two coexist, explicit parameters win.
@dynamicMemberLookup
public struct FlareStrings: Sendable {
    /// Starts with the Chinese defaults and applies typed overrides in one place.
    /// The bounded signature keeps default construction safe as the vocabulary grows.
    public init(_ configure: (inout FlareStringsTable) -> Void = { _ in }) {
        var table = FlareStringsTable()
        configure(&table)
        storage = Storage(table)
    }

    /// Every field reads and writes through here: `strings.send`, `strings.send = "Send"`, `\FlareStrings.send`.
    public subscript<Value>(dynamicMember keyPath: WritableKeyPath<FlareStringsTable, Value>) -> Value {
        get { storage.table[keyPath: keyPath] }
        set {
            if !isKnownUniquelyReferenced(&storage) { storage = Storage(storage.table) }
            storage.table[keyPath: keyPath] = newValue
        }
    }

    /// The copy is held by reference (copied on write), so a `FlareStrings` is one pointer wide. Every component
    /// reads it through `@Environment`, which stores the value inline: held by value, each component carried the
    /// whole table (about 16 KB), and a screen of nested components overflowed the 1 MB main thread stack of a
    /// device (not the 8 MB of the simulator).
    private var storage: Storage

    /// All the fields as one value, for code that walks every field (the kit's tests reflect over it).
    var table: FlareStringsTable { storage.table }

    private final class Storage: @unchecked Sendable {
        // Only mutated while uniquely referenced (the setter above copies first), so no other thread can see it.
        var table: FlareStringsTable
        init(_ table: FlareStringsTable) { self.table = table }
    }
}

